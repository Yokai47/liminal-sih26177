"""Replay a recorded ground-station session through the Verilog engine.

The engine log holds the starting state and every packet's drone positions. This
script (1) replays them through the integer model and checks that it reproduces the
headings the ground station actually received over UDP, then (2) writes testbench
files so Icarus Verilog runs the SAME session through fpga/rtl/vicsek_engine.v and
compares every agent after every step.

    python -m groundstation.rtl_replay gs_run [steps]
"""
import os
import subprocess
import sys
import numpy as np

from groundstation.common import ROOT
from liminal_sim import fixedpoint as fp

SIM = os.path.join(ROOT, "fpga", "sim")


def replay(run_dir, steps=40, name="replay_session"):
    e = dict(np.load(os.path.join(run_dir, "engine.npz")))
    g = dict(np.load(os.path.join(run_dir, "gs.npz")))
    x, y, h, s = [a.astype(np.int64).copy() for a in e["init"]]
    rq2, vq, lo, hi, wlo, whi, wk = [int(v) for v in e["wp"]]
    n = len(x)
    first = int(e["first"][0]); nr = e["wx"].shape[1]
    hm = np.zeros(n, dtype=np.int64)
    gs_h = {int(sq): row for sq, row, ok in zip(g["seq"], g["h"], g["ok"]) if ok}
    rows, wrows = [], []
    dump = lambda: rows.extend(f"{x[i]:04x}{y[i]:04x}{h[i]:04x}{s[i]:08x}" for i in range(n))
    dump()
    match = checked = 0
    total = min(steps, len(e["seq"]))
    for k in range(len(e["seq"])):
        if (e["wx"][k] >= 0).all():
            x[first:first + nr] = e["wx"][k]; y[first:first + nr] = e["wy"][k]
            if k < total:
                wrows += [f"{first + d:04x}{x[first + d]:04x}{y[first + d]:04x}{h[first + d]:04x}{s[first + d]:08x}"
                          for d in range(nr)]
        fp.step_walls(x, y, h, s, rq2, vq, int(e["etaq"][k]), lo, hi, wlo, whi, wk, hm)
        if k < total:
            dump()
        sq = int(e["seq"][k])
        if sq in gs_h:
            checked += 1
            match += int(np.array_equal(gs_h[sq], h))
    with open(os.path.join(SIM, f"test_{name}.mem"), "w") as f:
        f.write("\n".join(rows[: (total + 1) * n]) + "\n")
    with open(os.path.join(SIM, f"test_{name}_w.mem"), "w") as f:
        f.write("\n".join(wrows) + "\n")
    aw = max((n - 1).bit_length(), 1)
    etaq = int(e["etaq"][0])
    vh = [f"// Generated by groundstation/rtl_replay.py from a recorded ground-station session",
          f"localparam T_N = {n};", f"localparam T_AW = {aw};", f"localparam T_STEPS = {total};",
          f"localparam [31:0] T_RQ2 = 32'd{rq2};", f"localparam [15:0] T_VQ = 16'd{vq};",
          f"localparam [16:0] T_ETAQ = 17'd{etaq};", f'localparam T_MEM = "test_{name}.mem";',
          "localparam T_WALLS = 1;", f"localparam [15:0] T_LO = 16'd{lo};", f"localparam [15:0] T_HI = 16'd{hi};",
          f"localparam [15:0] T_WLO = 16'd{wlo};", f"localparam [15:0] T_WHI = 16'd{whi};",
          f"localparam [23:0] T_WK = 24'd{wk};", f"localparam T_NW = {nr};", f'localparam T_WMEM = "test_{name}_w.mem";']
    with open(os.path.join(SIM, f"test_{name}.vh"), "w") as f:
        f.write("\n".join(vh) + "\n")
    assert (e["etaq"][:total] == etaq).all(), "noise changed during the replayed steps"
    return dict(steps_logged=int(len(e["seq"])), headings_checked=checked, headings_matching=match,
                rtl_steps=total, name=name)


def run_iverilog(name="replay_session", lanes=16):
    out = os.path.join(SIM, "replay.vvp")
    subprocess.run(["iverilog", "-g2012", "-I", "../rtl", "-I", ".", f'-DTEST_VH="test_{name}.vh"', f"-Ptb.P={lanes}",
                    "-o", out, "tb_vicsek_engine.v", "../rtl/vicsek_engine.v"], cwd=SIM, check=True)
    res = subprocess.run(["vvp", "-n", out], cwd=SIM, capture_output=True, text=True).stdout
    return [l for l in res.splitlines() if l.startswith(("PASS", "FAIL", "MISMATCH"))]


if __name__ == "__main__":
    r = replay(sys.argv[1] if len(sys.argv) > 1 else "gs_run", int(sys.argv[2]) if len(sys.argv) > 2 else 40)
    print(f"integer model reproduces {r['headings_matching']} of {r['headings_checked']} received heading sets")
    print("\n".join(run_iverilog(r["name"])))
