"""Generate the FPGA data files from the Python reference model, so the RTL and
the model can never disagree about a table value.

  fpga/rtl/trig_lut_init.vh   1024-entry cos/sin ROM contents (Q1.15)
  fpga/rtl/atan_tab.vh        CORDIC arctangent table (20-bit: 16 + 4 fraction bits)
  fpga/sim/test_<name>.mem    expected agent states, step 0..STEPS (x y h rng, 80 bits per line)
  fpga/sim/test_<name>.vh     test parameters (N, RQ2, VQ, ETAQ, STEPS, wall constants)
  fpga/sim/test_<name>_w.mem  walled tests only: the laptop's writes before each step
                              (address + state with camera-measured x, y for each drone)
Run from the repo root:  python fpga/gen_rtl_data.py
"""
import math, os, sys
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from liminal_sim import fixedpoint as fp

R = os.path.join(os.path.dirname(__file__), "rtl")
S = os.path.join(os.path.dirname(__file__), "sim")


def h16(v):
    return f"{int(v) & 0xFFFF:04x}"


def write_luts():
    lines = ["// Generated by fpga/gen_rtl_data.py from liminal_sim/fixedpoint.py. Do not edit.",
             "// cos/sin ROM: index k = round(h / 64) mod 1024, value = round(32767 * cos(2*pi*k/1024))",
             "initial begin"]
    for k in range(fp.LUT_N):
        lines.append(f"  cos_lut[{k}] = 16'h{h16(fp.COS_LUT[k])}; sin_lut[{k}] = 16'h{h16(fp.SIN_LUT[k])};")
    lines.append("end")
    open(os.path.join(R, "trig_lut_init.vh"), "w").write("\n".join(lines) + "\n")
    lines = ["// Generated by fpga/gen_rtl_data.py. CORDIC table: round(atan(2^-i) * 2^20 / (2*pi))",
             "function signed [21:0] atan_tab(input [4:0] i);", "  begin", "    case (i)"]
    for i, v in enumerate(fp.ATAN_TAB):
        lines.append(f"      5'd{i}: atan_tab = 22'sd{int(v)};")
    lines += ["      default: atan_tab = 22'sd0;", "    endcase", "  end", "endfunction"]
    open(os.path.join(R, "atan_tab.vh"), "w").write("\n".join(lines) + "\n")


def write_test(name, n, eta, steps, seed, density=2.0, v0=0.03):
    L = math.sqrt(n / density)
    p = fp.Params(L, 1.0, v0, eta)
    x, y, h, s = fp.init_state(n, seed)
    hm = np.zeros(n, dtype=np.int64)
    rows = []
    def dump():
        for i in range(n):
            rows.append(f"{x[i]:04x}{y[i]:04x}{h[i]:04x}{s[i]:08x}")
    dump()
    for _ in range(steps):
        fp.step(x, y, h, s, p.rq2, p.vq, p.etaq, hm)
        dump()
    open(os.path.join(S, f"test_{name}.mem"), "w").write("\n".join(rows) + "\n")
    write_vh(name, n, steps, p, f"{n} agents, eta={eta}, {steps} steps, L={L:.4f}")
    return p


def write_vh(name, n, steps, p, desc, walls=None, nw=0):
    aw = max(int(math.ceil(math.log2(n))), 1)
    w = walls
    vh = [f"// Generated by fpga/gen_rtl_data.py: {desc}",
          f"localparam T_N = {n};", f"localparam T_AW = {aw};", f"localparam T_STEPS = {steps};",
          f"localparam [31:0] T_RQ2 = 32'd{p.rq2};", f"localparam [15:0] T_VQ = 16'd{p.vq};",
          f"localparam [16:0] T_ETAQ = 17'd{p.etaq};", f'localparam T_MEM = "test_{name}.mem";',
          f"localparam T_WALLS = {1 if w else 0};",
          f"localparam [15:0] T_LO = 16'd{w.lo if w else 0};", f"localparam [15:0] T_HI = 16'd{w.hi if w else 0};",
          f"localparam [15:0] T_WLO = 16'd{w.wlo if w else 0};", f"localparam [15:0] T_WHI = 16'd{w.whi if w else 0};",
          f"localparam [23:0] T_WK = 24'd{w.wk if w else 0};",
          f"localparam T_NW = {nw};", f'localparam T_WMEM = "test_{name}_w.mem";']
    open(os.path.join(S, f"test_{name}.vh"), "w").write("\n".join(vh) + "\n")


def write_test_walls(name, n_virtual, n_real, eta, steps, seed, drones_roam=True):
    """Walled arena (v1.1). Agents n_virtual.. are the real drones: before every step the
    'laptop' overwrites their x, y with a camera measurement. Here the measurement is a
    made-up path that wanders over the WHOLE net, including outside the flock boundary
    and right up to the edges, so the reflection and signed-arithmetic paths are exercised."""
    n = n_virtual + n_real
    wp = fp.WallParams(eta=eta)
    x, y, h, s = fp.init_walled(n, wp, seed)
    r = np.random.default_rng(seed + 1)
    hm = np.zeros(n, dtype=np.int64)
    rows, wrows = [], []
    def dump():
        for i in range(n):
            rows.append(f"{x[i]:04x}{y[i]:04x}{h[i]:04x}{s[i]:08x}")
    dump()
    # drone paths: start anywhere in the net, random-walk in steps of up to ~3 cm
    px = r.uniform(0, 65535, n_real); py = r.uniform(0, 65535, n_real)
    px[0], py[0] = 10.0, 65530.0          # one drone parked in a corner, outside the boundary
    for _ in range(steps):
        if drones_roam:
            px = np.clip(px + r.normal(0, 400, n_real), 0, 65535); py = np.clip(py + r.normal(0, 400, n_real), 0, 65535)
            px[0], py[0] = 10.0, 65530.0
        for d in range(n_real):
            i = n_virtual + d
            x[i] = int(round(px[d])); y[i] = int(round(py[d]))
            wrows.append(f"{i:04x}{x[i]:04x}{y[i]:04x}{h[i]:04x}{s[i]:08x}")
        fp.step_walls(x, y, h, s, wp.rq2, wp.vq, wp.etaq, wp.lo, wp.hi, wp.wlo, wp.whi, wp.wk, hm)
        dump()
    open(os.path.join(S, f"test_{name}.mem"), "w").write("\n".join(rows) + "\n")
    open(os.path.join(S, f"test_{name}_w.mem"), "w").write("\n".join(wrows) + "\n")
    write_vh(name, n, steps, wp, f"walled arena, {n_virtual} virtual + {n_real} drones, eta={eta}, {steps} steps",
             walls=wp, nw=n_real)
    return wp


if __name__ == "__main__":
    write_luts()
    write_test("n64", 64, 1.5, 32, 2026)
    write_test("n256", 256, 2.6, 16, 7)
    write_test("n64_ordered", 64, 0.3, 32, 11)
    write_test_walls("walls_n128", 120, 8, 1.0, 40, 31)        # the demo flock
    write_test_walls("walls_n64_noisy", 56, 8, 4.0, 40, 32)    # disordered, lots of wall contact
    print("written")
